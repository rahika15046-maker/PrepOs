export const DSA_CATALOG = P.map(([title, leetcodeSlug, topic, pattern, difficulty]) => ({
  title,
  leetcodeSlug,
  topic,
  pattern,
  difficulty,
  url: `https://leetcode.com/problems/${leetcodeSlug}/`,
  importance: difficulty === 'Hard' ? 6 : difficulty === 'Medium' ? 8 : 6,
  estimatedMinutes: difficulty === 'Hard' ? 75 : difficulty === 'Medium' ? 45 : 25,
}))

/**
 * Idempotent: upserts by LeetCode slug (and adopts old slug-less seed rows by
 * title), so users' existing DSAProgress references stay valid.
 */
export async function ensureDsaCatalog() {
  const ops = DSA_CATALOG.map((p) => ({
    updateOne: {
      filter: {
        $or: [
          { leetcodeSlug: p.leetcodeSlug },
          { title: p.title, $or: [{ leetcodeSlug: { $exists: false } }, { leetcodeSlug: '' }, { leetcodeSlug: null }] },
        ],
      },
      update: { $set: p },
      upsert: true,
    },
  }))

  const result = await DSAProblem.bulkWrite(ops, { ordered: false })
  return { upserted: result.upsertedCount, modified: result.modifiedCount, total: DSA_CATALOG.length }
}
